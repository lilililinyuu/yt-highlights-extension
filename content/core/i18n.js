  function autoDetect() {
    const l = (navigator.language || '').toLowerCase();
    if (l.startsWith('ja')) return 'ja';
    if (l.startsWith('zh')) return 'zh';
    return 'en';
  }

  let lang = autoDetect();

  YTEX.i18n = {
    init() {
      try {
        chrome.storage.local.get(['ytexLang'], d => {
          if (chrome.runtime.lastError || !d) return;
          const v = d.ytexLang;
          lang = !v || v === 'auto' ? autoDetect() : v;
          if (typeof this.onLangChange === 'function') this.onLangChange();
        });
      } catch {}
    },
    setLang(v) {
      lang = !v || v === 'auto' ? autoDetect() : v;
      try { chrome.storage.local.set({ ytexLang: lang }); } catch {}
      if (typeof this.onLangChange === 'function') this.onLangChange();
    },
    get lang() { return lang; },
    // t(中文原文, ...参数)：返回当前语言文案；缺失时回退中文
    t(key, ...args) {
      const d = DICT[lang];
      let s = (d && d[key]) || key;
      args.forEach((a, i) => { s = s.replace(`{${i}}`, String(a)); });
      return s;
    },
  };
